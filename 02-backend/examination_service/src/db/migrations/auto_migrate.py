"""Automated database migration handler with connectivity checks and safe upgrades."""

import logging
import time
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.script import Script, ScriptDirectory
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import create_engine, exc, text
from sqlalchemy.engine import Engine
from sqlalchemy.engine.url import make_url

from src.config.settings import settings

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


def validate_database_connection(engine: Engine, max_retries: int = 3, retry_delay: float = 2.0) -> bool:
    """Verifies database connectivity with retry logic.

    Args:
        engine: Initialized SQLAlchemy engine instance
        max_retries: Maximum connection attempts (default: 3)
        retry_delay: Delay between retries in seconds (default: 2.0)

    Returns:
        bool: True if connection succeeds, False otherwise

    Example:
        >>> engine = create_engine("postgresql://user:pass@localhost/db")
        >>> validate_database_connection(engine)
        True
    """
    for attempt in range(max_retries):
        try:
            with engine.connect() as conn:
                conn.execute(text("SELECT 1"))
            logger.info("Database connection successful")
            return True
        except exc.OperationalError as e:
            logger.warning(f"Connection attempt {attempt + 1}/{max_retries} failed: {e!s}")
            if attempt < max_retries - 1:
                time.sleep(retry_delay)
    return False


def initialize_alembic_config() -> tuple[Config, Engine]:
    """Initializes Alembic configuration with environment validation.

    Returns:
        Tuple containing:
            - Config: Initialized Alembic config object
            - Engine: SQLAlchemy engine instance

    Raises:
        ValueError: If DATABASE_URL is not set or invalid
        RuntimeError: If database connection fails
    """
    db_url = settings.DATABASE_URL.replace("+asyncpg", "")
    if not db_url:
        raise ValueError("DATABASE_URL environment variable not set")

    parsed_url = make_url(db_url)
    logger.info(f"Connecting to database at {parsed_url.host}:{parsed_url.port}")

    try:
        engine = create_engine(db_url)
        if not validate_database_connection(engine):
            raise RuntimeError("Could not connect to database after retries")

        migrations_dir = Path(__file__).resolve().parent

        alembic_cfg = Config()
        alembic_cfg.set_main_option("script_location", str(migrations_dir))
        alembic_cfg.set_main_option("sqlalchemy.url", db_url)

        return alembic_cfg, engine
    except exc.SQLAlchemyError as e:
        raise RuntimeError(f"Database initialization failed: {e!s}") from e


def check_and_fix_missing_revision(alembic_cfg: Config, engine: Engine) -> None:
    """Checks if the database revision exists in migration files and fixes if missing.

    If the database has a revision that doesn't exist in the migration files,
    this function stamps the database to HEAD (or baseline if no migrations exist).

    Args:
        alembic_cfg: Alembic configuration object
        engine: SQLAlchemy engine instance
    """
    try:
        script = ScriptDirectory.from_config(alembic_cfg)

        # Get current revision from database
        with engine.connect() as conn:
            result = conn.execute(text("SELECT version_num FROM alembic_version"))
            row = result.fetchone()
            if row:
                current_rev = row[0]
                try:
                    # Try to find the revision in the script directory
                    script.get_revision(current_rev)
                    logger.info(f"Current database revision {current_rev} is valid")
                except Exception:
                    # Revision doesn't exist in migration files
                    logger.warning(
                        f"Database revision {current_rev} not found in migration files. Stamping database to HEAD..."
                    )
                    command.stamp(alembic_cfg, "head")
                    logger.info("Database stamped to HEAD revision")
    except exc.ProgrammingError:
        # alembic_version table doesn't exist, which is fine
        logger.info("No alembic_version table found, database is uninitialized")
    except Exception as e:
        logger.warning(f"Could not check database revision: {e!s}")


def run_auto_migrations() -> None:
    """Orchestrates the complete migration workflow.

    Workflow:
        1. Validates database connection
        2. Checks and fixes missing revisions
        3. Applies pending migrations
        4. Detects model changes
        5. Generates and applies new migrations if needed

    Raises:
        SystemExit: With status code 1 on any critical failure
    """
    alembic_cfg: Config | None = None
    try:
        alembic_cfg, engine = initialize_alembic_config()

        # Step 0: Check and fix missing revisions
        check_and_fix_missing_revision(alembic_cfg, engine)

        # Step 1: Ensure HEAD revision
        logger.info("Synchronizing database to HEAD revision...")
        try:
            command.upgrade(alembic_cfg, "head")
        except Exception as upgrade_error:
            # If upgrade fails due to missing revision, try stamping again
            if "Can't locate revision" in str(upgrade_error):
                logger.warning("Upgrade failed due to missing revision, stamping to HEAD...")
                command.stamp(alembic_cfg, "head")
                logger.info("Database stamped to HEAD, retrying upgrade...")
                command.upgrade(alembic_cfg, "head")
            else:
                raise

        # Step 2: Check for model changes
        logger.info("Validating model-database alignment...")
        command.check(alembic_cfg)
        logger.info("Database schema matches models")

    except AutogenerateDiffsDetected:
        # Step 3: Handle model changes
        if alembic_cfg is None:
            # Unreachable: AutogenerateDiffsDetected is only raised by command.check(),
            # which runs after alembic_cfg is assigned.
            raise
        logger.info("Detected schema differences, generating migration...")
        revision = command.revision(alembic_cfg, autogenerate=True, message="auto-generated migration")
        if isinstance(revision, Script):
            logger.info(f"Generated revision ID: {revision.revision}")

        logger.info("Applying generated migration...")
        command.upgrade(alembic_cfg, "head")
        logger.info("Migration applied successfully")

    except Exception as e:
        logger.error(f"Migration aborted: {type(e).__name__} - {e!s}", exc_info=True)
        raise SystemExit(1) from e


if __name__ == "__main__":
    run_auto_migrations()
