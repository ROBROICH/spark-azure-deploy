import { type TProperties, TypeGuard } from "@sinclair/typebox";
import { $ } from "bun";
import { isString } from "es-toolkit";
import { resolve } from "node:path";

import * as contracts from "../src/contracts/index.js";

const repository = resolve(import.meta.dirname, "../../../..");
const output = resolve(repository, "packages/temporal/python/src/temporal/contracts.py");
const registryOutput = resolve(repository, "packages/temporal/python/src/temporal/registry.py");
const definitions: TProperties = {};
const workflows: [string, string][] = [];
const taskQueues: [string, string][] = [];

for (const [exportName, imported] of Object.entries(contracts)) {
  if (!TypeGuard.IsImport(imported)) {
    if (exportName.endsWith("_WORKFLOW") && isString(imported))
      workflows.push([exportName, imported]);
    if (exportName.endsWith("_TASK_QUEUE") && isString(imported))
      taskQueues.push([exportName.slice(0, -"_TASK_QUEUE".length), imported]);
    continue;
  }
  for (const [name, schema] of Object.entries(imported.$defs)) {
    if (!TypeGuard.IsSchema(schema)) throw new TypeError(`Invalid TypeBox contract: ${name}`);
    const current = definitions[name];
    if (current && JSON.stringify(current) !== JSON.stringify(schema)) {
      throw new Error(`Conflicting TypeBox contract: ${name}`);
    }
    definitions[name] = schema;
  }
}

if (!definitions.WorkflowStatusEvent) throw new Error("No TypeBox contracts found");
if (workflows.length === 0) throw new Error("No Temporal workflows found");

const queueFor = (workflow: string) => {
  const matches = taskQueues.filter(([prefix]) => workflow.startsWith(`${prefix}_`));
  const longest = Math.max(...matches.map(([prefix]) => prefix.length));
  const queues = matches.filter(([prefix]) => prefix.length === longest);
  if (queues.length !== 1) throw new Error(`Expected one task queue for ${workflow}`);
  return queues[0]![1];
};

const schema = JSON.stringify(
  {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $defs: definitions,
    $ref: "WorkflowStatusEvent",
  },
  (key, value) => {
    if (key === "$id") return undefined;
    if (key === "$ref") return `#/$defs/${value}`;
    return value;
  },
);

const registry = `# @generated by packages/temporal/contracts/scripts/generate.ts
from datetime import datetime
from typing import Annotated, NamedTuple, NewType
from uuid import UUID, uuid4

from pydantic import Field

WorkflowName = NewType("WorkflowName", str)
GeneratedDateTime = Annotated[datetime, Field(default_factory=datetime.now)]
GeneratedStringId = Annotated[str, Field(default_factory=lambda: str(uuid4()))]
GeneratedUUID = Annotated[UUID, Field(default_factory=uuid4)]


class WorkflowDefinition(NamedTuple):
    name: WorkflowName
    task_queue: str


${workflows
  .sort(([left], [right]) => left.localeCompare(right))
  .map(
    ([name, workflow]) =>
      `${name} = WorkflowDefinition(WorkflowName(${JSON.stringify(workflow)}), ${JSON.stringify(queueFor(name))})`,
  )
  .join("\n")}
`;

const typeOverrides = JSON.stringify({
  GeneratedDateTime: "temporal.registry.GeneratedDateTime",
  GeneratedStringId: "temporal.registry.GeneratedStringId",
  GeneratedUUID: "temporal.registry.GeneratedUUID",
});
await Promise.all([
  $`uv run datamodel-codegen --input-file-type jsonschema --schema-version 2020-12 --output-model-type pydantic_v2.BaseModel --target-python-version 3.13 --class-name WorkflowStatusEvent --output ${output} --base-class temporal.contracts_base.CamelWireModel --capitalise-enum-members --custom-file-header "# ruff: noqa: PLC2401" --custom-file-header-mode prepend --disable-timestamp --enable-generated-header-marker --output-datetime-class datetime --snake-case-field --strict-nullable --strict-refs --strict-types str bytes int float bool --type-overrides ${typeOverrides} --use-annotated --use-serialization-alias --use-standard-collections --use-type-alias --use-union-operator --formatters isort ruff-check ruff-format < ${new Blob([schema])}`.cwd(
    repository,
  ),
  Bun.write(registryOutput, registry),
]);

await $`uv run ruff check --fix --select I001 ${output}`.cwd(repository);
