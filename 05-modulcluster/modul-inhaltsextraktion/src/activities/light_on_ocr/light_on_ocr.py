"""Light ON OCR Preprocessing and Extraction.

This module provides the necessary schemas, utility functions, and Temporal
activities to convert PDF pages into base64 images, correct their rotation,
and extract markdown text using a Vision Language Model (VLM).
"""

import base64
import io
import re
from datetime import timedelta

import pypdfium2 as pdfium
from pydantic import BaseModel
from temporal.activities.vlm import vlm_invoke
from temporalio import activity, workflow
from temporalio.common import RetryPolicy

from src.activities.light_on_ocr.preprocessing import PageImage, RotationDetector
from src.config import get_config


class PreparePDFPageImagesOutput(BaseModel):
    """Output schema for PDF page image preparation.

    Attributes:
        page_images_b64 (list[str]): A list of base64-encoded strings,
            each representing a properly rotated PNG image of a PDF page.
    """

    page_images_b64: list[str]


def strip_artifacts(text: str) -> str:
    """Unwrap LaTeX lines and strip trailing notes generated by LightOnOcr."""
    latex_tags = [
        "text",
        "textbf",
        "textit",
        "texttt",
        "emph",
        "mathrm",
        "mathbf",
        "mathit",
        "mathcal",
        "mathbb",
        "cdot",
        "quad",
        "qquad",
        "boxed",
        "overline",
        "underline",
        "left",
        "right",
        "lambda",
    ]
    tag_alt = "|".join(latex_tags)
    # Removes $ of Latex Tags
    text = re.sub(rf"\$([^$\n]*\\(?:{tag_alt})[^$\n]*)\$", r"\1", text)
    # Removes Latex tags with curly brackets keeping the text
    text = re.sub(rf"\\(?:{tag_alt})\s*\{{([^}}]*)\}}", r"\1", text)
    # Removes Latex tags
    text = re.sub(rf"\\(?:{tag_alt})\b\s?", "", text)
    text = re.sub(r"\n{2,}\s*Note:[^\n]*\s*\Z", "", text, flags=re.IGNORECASE)
    return text.strip()


@activity.defn(name="prepare_pdf_page_images")
async def _prepare_pdf_page_images(file_bytes: bytes) -> PreparePDFPageImagesOutput:
    """Renders PDF pages to base64 images and applies rotation correction."""
    activity.logger.debug("Starting PDF page image preparation activity.")
    cfg = get_config()

    # Step 1: Load PDF document
    src_pdf = pdfium.PdfDocument(file_bytes)
    num_pages = len(src_pdf)

    if num_pages == 0:
        activity.logger.debug("Empty PDF received, returning empty list.")
        return PreparePDFPageImagesOutput(page_images_b64=[])

    page_images_b64 = []

    # Step 2: Render pages, correct rotation, and encode to base64
    for page in src_pdf:
        pil_image = page.render(scale=2.77).to_pil()
        buffer = io.BytesIO()
        pil_image.save(buffer, format="PNG")
        image_base64 = base64.b64encode(buffer.getvalue()).decode("utf-8")

        page_img = PageImage(b64=image_base64)
        rotation = RotationDetector(
            page_img,
            rotation_threshold=cfg.OCR_ROTATION_THRESHOLD,
            flip_threshold=cfg.OCR_FLIP_THRESHOLD,
        ).detect()

        page_img.rotate(degrees=rotation.angle)
        page_images_b64.append(page_img.to_light_on_ocr_b64())

    activity.logger.info(f"Successfully prepared {len(page_images_b64)} page images.")
    return PreparePDFPageImagesOutput(page_images_b64=page_images_b64)


async def prepare_pdf_page_images(file_bytes: bytes) -> PreparePDFPageImagesOutput:
    """Workflow wrapper for executing the PDF page preparation activity."""
    return await workflow.execute_activity(
        _prepare_pdf_page_images,
        file_bytes,
        start_to_close_timeout=timedelta(minutes=10),
        retry_policy=RetryPolicy(maximum_attempts=get_config().TEMPORAL_PREPROCESSING_ACTIVITY_MAX_ATTEMPTS),
    )


async def extract_markdown(b64: str) -> str:
    """Invokes the VLM to extract markdown from a base64-encoded image."""
    cfg = get_config()
    vlm_text = await vlm_invoke(
        image_b64=b64,
        image_mime="image/png",
        system_prompt="",
        prompt="",
        model=cfg.LIGHT_ON_OCR_MODEL,
        max_completion_tokens=cfg.LIGHT_ON_OCR_MAX_COMPLETION_TOKENS,
        temperature=cfg.LIGHT_ON_OCR_TEMPERATURE,
        top_p=cfg.LIGHT_ON_OCR_TOP_P,
        frequency_penalty=cfg.LIGHT_ON_OCR_FREQUENCY_PENALTY,
        presence_penalty=cfg.LIGHT_ON_OCR_PRESENCE_PENALTY,
    )

    sanitized_text = strip_artifacts(vlm_text)
    return sanitized_text
