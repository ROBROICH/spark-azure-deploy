#!/bin/sh
set -eu

# This script runs when the container starts.
# Goal: inject stage-specific runtime configuration into the already-built frontend.

INDEX_HTML_PATH="/usr/share/nginx/html/index.html"
API_BASE_URL_PLACEHOLDER="__VITE_API_BASE_URL__"
APP_BASE_PATH_PLACEHOLDER="__VITE_APP_BASE_PATH__"
TEMPORAL_UI_BASE_URL_PLACEHOLDER="__VITE_TEMPORAL_UI_BASE_URL__"
ALLOWED_DOWNLOAD_ORIGINS_PLACEHOLDER="__VITE_ALLOWED_DOWNLOAD_ORIGINS__"
ALLOWED_UPLOAD_ORIGINS_PLACEHOLDER="__VITE_ALLOWED_UPLOAD_ORIGINS__"
SENTRY_DSN_PLACEHOLDER="__VITE_SENTRY_DSN__"
SENTRY_ENVIRONMENT_PLACEHOLDER="__VITE_SENTRY_ENVIRONMENT__"
ENABLE_EWMS_FEATURE_PLACEHOLDER="__VITE_ENABLE_EWMS_FEATURE__"
ENABLE_AUTH_REDIRECT_RETRY_PLACEHOLDER="__VITE_ENABLE_AUTH_REDIRECT_RETRY__"
ENABLE_MAINTENANCE_MODE_PLACEHOLDER="__VITE_ENABLE_MAINTENANCE_MODE__"
SYSTEM_LOAD_DISABLE_THRESHOLD_PERCENTAGE_PLACEHOLDER="__VITE_SYSTEM_LOAD_DISABLE_THRESHOLD_PERCENTAGE__"
ENABLE_DOCUMENT_VERSIONING_FEATURE_PLACEHOLDER="__VITE_ENABLE_DOCUMENT_VERSIONING_FEATURE__"
DANGEROUS_ENABLE_ROLE_SWITCHER_PLACEHOLDER="__VITE_DANGEROUS_ENABLE_ROLE_SWITCHER__"
ALLOW_DEV_MODE_PLACEHOLDER="__ALLOW_DEV_MODE__"

# 1) Validate required runtime env var.
if [ -z "${VITE_API_BASE_URL:-}" ]; then
  echo "ERROR: VITE_API_BASE_URL is not set"
  exit 1
fi

# 2) Validate expected HTML file exists.
if [ ! -f "$INDEX_HTML_PATH" ]; then
  echo "ERROR: Cannot find $INDEX_HTML_PATH"
  exit 1
fi

# 3) Escape only characters that break sed replacement.
# We use '|' as the sed separator, so we escape '&' and '|'.
ESCAPED_API_BASE_URL=$(printf '%s' "$VITE_API_BASE_URL" | sed 's/[&|]/\\&/g')
APP_BASE_PATH=${VITE_APP_BASE_PATH:-/app}
ESCAPED_APP_BASE_PATH=$(printf '%s' "$APP_BASE_PATH" | sed 's/[&|]/\\&/g')
SENTRY_DSN=${VITE_SENTRY_DSN:-}
SENTRY_ENVIRONMENT=${VITE_SENTRY_ENVIRONMENT:-}
ENABLE_EWMS_FEATURE=${VITE_ENABLE_EWMS_FEATURE:-false}
ENABLE_AUTH_REDIRECT_RETRY=${VITE_ENABLE_AUTH_REDIRECT_RETRY:-true}
ENABLE_MAINTENANCE_MODE=${VITE_ENABLE_MAINTENANCE_MODE:-false}
SYSTEM_LOAD_DISABLE_THRESHOLD_PERCENTAGE=${VITE_SYSTEM_LOAD_DISABLE_THRESHOLD_PERCENTAGE:-500}
ENABLE_DOCUMENT_VERSIONING_FEATURE=${VITE_ENABLE_DOCUMENT_VERSIONING_FEATURE:-true}
DANGEROUS_ENABLE_ROLE_SWITCHER=${VITE_DANGEROUS_ENABLE_ROLE_SWITCHER:-false}
ALLOW_DEV_MODE=${ALLOW_DEV_MODE:-false}
TEMPORAL_UI_BASE_URL=${VITE_TEMPORAL_UI_BASE_URL:-}
ALLOWED_DOWNLOAD_ORIGINS=${VITE_ALLOWED_DOWNLOAD_ORIGINS:-}
ALLOWED_UPLOAD_ORIGINS=${VITE_ALLOWED_UPLOAD_ORIGINS:-}

ESCAPED_SENTRY_DSN=$(printf '%s' "$SENTRY_DSN" | sed 's/[&|]/\\&/g')
ESCAPED_SENTRY_ENVIRONMENT=$(printf '%s' "$SENTRY_ENVIRONMENT" | sed 's/[&|]/\\&/g')
ESCAPED_ENABLE_EWMS_FEATURE=$(printf '%s' "$ENABLE_EWMS_FEATURE" | sed 's/[&|]/\\&/g')
ESCAPED_ENABLE_AUTH_REDIRECT_RETRY=$(printf '%s' "$ENABLE_AUTH_REDIRECT_RETRY" | sed 's/[&|]/\\&/g')
ESCAPED_ENABLE_MAINTENANCE_MODE=$(printf '%s' "$ENABLE_MAINTENANCE_MODE" | sed 's/[&|]/\\&/g')
ESCAPED_SYSTEM_LOAD_DISABLE_THRESHOLD_PERCENTAGE=$(printf '%s' "$SYSTEM_LOAD_DISABLE_THRESHOLD_PERCENTAGE" | sed 's/[&|]/\\&/g')
ESCAPED_ENABLE_DOCUMENT_VERSIONING_FEATURE=$(printf '%s' "$ENABLE_DOCUMENT_VERSIONING_FEATURE" | sed 's/[&|]/\\&/g')
ESCAPED_DANGEROUS_ENABLE_ROLE_SWITCHER=$(printf '%s' "$DANGEROUS_ENABLE_ROLE_SWITCHER" | sed 's/[&|]/\\&/g')
ESCAPED_ALLOW_DEV_MODE=$(printf '%s' "$ALLOW_DEV_MODE" | sed 's/[&|]/\\&/g')
ESCAPED_TEMPORAL_UI_BASE_URL=$(printf '%s' "$TEMPORAL_UI_BASE_URL" | sed 's/[&|]/\\&/g')
ESCAPED_ALLOWED_DOWNLOAD_ORIGINS=$(printf '%s' "$ALLOWED_DOWNLOAD_ORIGINS" | sed 's/[&|]/\\&/g')
ESCAPED_ALLOWED_UPLOAD_ORIGINS=$(printf '%s' "$ALLOWED_UPLOAD_ORIGINS" | sed 's/[&|]/\\&/g')

# 4) Replace placeholder in index.html with the runtime value.
sed -i "s|$API_BASE_URL_PLACEHOLDER|$ESCAPED_API_BASE_URL|g" "$INDEX_HTML_PATH"
sed -i "s|$APP_BASE_PATH_PLACEHOLDER|$ESCAPED_APP_BASE_PATH|g" "$INDEX_HTML_PATH"
sed -i "s|$TEMPORAL_UI_BASE_URL_PLACEHOLDER|$ESCAPED_TEMPORAL_UI_BASE_URL|g" "$INDEX_HTML_PATH"
sed -i "s|$ALLOWED_DOWNLOAD_ORIGINS_PLACEHOLDER|$ESCAPED_ALLOWED_DOWNLOAD_ORIGINS|g" "$INDEX_HTML_PATH"
sed -i "s|$ALLOWED_UPLOAD_ORIGINS_PLACEHOLDER|$ESCAPED_ALLOWED_UPLOAD_ORIGINS|g" "$INDEX_HTML_PATH"
sed -i "s|$SENTRY_DSN_PLACEHOLDER|$ESCAPED_SENTRY_DSN|g" "$INDEX_HTML_PATH"
sed -i "s|$SENTRY_ENVIRONMENT_PLACEHOLDER|$ESCAPED_SENTRY_ENVIRONMENT|g" "$INDEX_HTML_PATH"
sed -i "s|$ENABLE_EWMS_FEATURE_PLACEHOLDER|$ESCAPED_ENABLE_EWMS_FEATURE|g" "$INDEX_HTML_PATH"
sed -i "s|$ENABLE_AUTH_REDIRECT_RETRY_PLACEHOLDER|$ESCAPED_ENABLE_AUTH_REDIRECT_RETRY|g" "$INDEX_HTML_PATH"
sed -i "s|$ENABLE_MAINTENANCE_MODE_PLACEHOLDER|$ESCAPED_ENABLE_MAINTENANCE_MODE|g" "$INDEX_HTML_PATH"
sed -i "s|$SYSTEM_LOAD_DISABLE_THRESHOLD_PERCENTAGE_PLACEHOLDER|$ESCAPED_SYSTEM_LOAD_DISABLE_THRESHOLD_PERCENTAGE|g" "$INDEX_HTML_PATH"
sed -i "s|$ENABLE_DOCUMENT_VERSIONING_FEATURE_PLACEHOLDER|$ESCAPED_ENABLE_DOCUMENT_VERSIONING_FEATURE|g" "$INDEX_HTML_PATH"
sed -i "s|$DANGEROUS_ENABLE_ROLE_SWITCHER_PLACEHOLDER|$ESCAPED_DANGEROUS_ENABLE_ROLE_SWITCHER|g" "$INDEX_HTML_PATH"
sed -i "s|$ALLOW_DEV_MODE_PLACEHOLDER|$ESCAPED_ALLOW_DEV_MODE|g" "$INDEX_HTML_PATH"

# 5) Start nginx in foreground.
exec nginx -g 'daemon off;'
